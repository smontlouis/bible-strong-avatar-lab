export const translateChineseDynamicText = (text: string) => {
  const rules: Array<[RegExp, (...matches: string[]) => string]> = [
    [/^Passe à (.+) comme dans l’app$/, next => `像在应用中一样转为 ${next}`],
    [
      /^Rejoue (.+) au lieu de passer à (.+)$/,
      (state, next) => `重新播放 ${state}，而不是转为 ${next}`,
    ],
    [/^Passe à (.+) après (.+) s$/, (next, time) => `${time} 秒后转为 ${next}`],
    [/^Joue l’état une fois, puis passe à (.+)$/, next => `播放一次该状态，然后转为 ${next}`],
    [/^Modifier l’expression (.+)$/, value => `编辑表情 ${value}`],
    [/^Modifier (.+)$/, value => `编辑${value}`],
    [/^Supprimer (.+) \?$/, value => `删除${value}？`],
    [/^Ajouter une forme · (.+)$/, value => `添加形状 · ${value}`],
    [/^Réinitialiser la position et la rotation de (.+)$/, value => `重置${value}的位置和旋转`],
    [/^Animation en cours : (.+)$/, value => `当前动画：${value}`],
    [/^Mettre (.+) en pause$/, value => `暂停${value}`],
    [/^Sort (\d+) fois plus souvent$/, times => `出现频率为 ${times} 倍`],
    [/^Reprendre (.+)$/, value => `继续${value}`],
    [/^Arrêter (.+)$/, value => `停止${value}`],
    [/^(.+) expressions$/, value => `${value} 个表情`],
  ]

  for (const [pattern, replacement] of rules) {
    const match = text.match(pattern)
    if (match) return replacement(...match.slice(1))
  }
  return null
}
